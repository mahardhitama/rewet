// One rect for each run of the same character in a row.
export function iconRects(name) {
  const out = [];
  ICONS[name].forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const ch = row[x];
      let w = 1;
      while (row[x + w] === ch) w++;
      if (ch !== ' ') out.push({ x, y, w, fill: ch === '#' ? 'currentColor' : PAL[ch] });
      x += w;
    }
  });
  return out;
}

const NS = 'http://www.w3.org/2000/svg';
export function icon(name, px = 24) {
  const s = document.createElementNS(NS, 'svg');
  for (const [k, v] of Object.entries({ viewBox: '0 0 12 12', width: px, height: px, 'shape-rendering': 'crispEdges', 'aria-hidden': 'true' })) s.setAttribute(k, v);
  for (const r of iconRects(name)) {
    const e = document.createElementNS(NS, 'rect');
    for (const [k, v] of Object.entries({ x: r.x, y: r.y, width: r.w, height: 1, fill: r.fill })) e.setAttribute(k, v);
    s.append(e);
  }
  return s;
}

// The button text goes in .t, the hover tree at the left, the purpose icon at the right.
// Set the text later through .t, not textContent: textContent removes the icons.
export function withIcon(button, name) {
  const t = document.createElement('span'), tree = document.createElement('span'), pic = document.createElement('span');
  t.className = 't'; tree.className = 'tree'; pic.className = 'pic';
  t.append(...button.childNodes);
  tree.append(icon('tree')); pic.append(icon(name));
  button.append(tree, t, pic);
  return button;
}
